package team.cinenetwork.exception;

/**
 * Верхнеуровневая классификация ошибок: помогает вызывающему коду быстро понять,
 * «кто виноват» — входные данные, обработка или система.
 */
public enum ErrorCategory {

    /** Ошибка аргументов или входных данных. */
    VALIDATION,

    /** Ошибка на этапе транскода/генерации артефактов. */
    PROCESSING,

    /** Прерывания и сбои ОС. */
    SYSTEM
}
